def get_ukrainian_curse_advice(detected_phrase_or_word: str) -> Optional[str]:
    """
    Знаходить відповідник для російського мату та формує рекомендацію солов'їною.
    """
    if not detected_phrase_or_word:
        return None

    word_lower = detected_phrase_or_word.lower().strip()
    
    # Прямий пошук
    if word_lower in RUSSIAN_CURSES_MAP:
        variants = RUSSIAN_CURSES_MAP[word_lower]
        chosen = random.sample(variants, min(2, len(variants)))
        return f"Не кажи «{detected_phrase_or_word}» — кажи <b>«{'»</b> або <b>«'.join(chosen)}»</b>!"

    # Пошук за входженням основи/кореня
    for curse_key, ukr_variants in RUSSIAN_CURSES_MAP.items():
        if curse_key in word_lower or word_lower in curse_key:
            chosen = random.sample(ukr_variants, min(2, len(ukr_variants)))
            return f"Не кажи «{detected_phrase_or_word}» — кажи <b>«{'»</b> або <b>«'.join(chosen)}»</b>!"

    return None
