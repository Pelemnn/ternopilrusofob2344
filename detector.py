def detect_russian(text: str) -> Tuple[bool, Optional[str], Optional[str]]:
    """
    Аналізує вхідний текст на наявність російської мови, мату та одруківок.
    
    Повертає:
        (is_russian: bool, reason: Optional[str], detected_sample: Optional[str])
    """
    if not text or not text.strip():
        return False, None, None

    # Нормалізуємо для пошуку обходів (leetspeak)
    norm_text = normalize_leetspeak(text)

    # 1. Перевірка на унікальні російські літери: ы, ё, ъ, э
    for src in (text, norm_text):
        for char in src:
            if char in RUSSIAN_ONLY_CHARS:
                words = src.split()
                sample = char
                for w in words:
                    if char in w:
                        sample = w.strip(".,!?\"'():;`~[]{}<>")
                        break
                return True, f"виявлено російську літеру «{char}»", sample

    # 2. Перевірка на сталі фрази (включно з лайками)
    lower_text = text.lower()
    norm_lower_text = norm_text.lower()
    for phrase, phrase_reason in RUSSIAN_PHRASES:
        if phrase in lower_text or phrase in norm_lower_text:
            return True, phrase_reason, phrase

    # 3. Перевірка за регулярними виразами (морфологія: закінчення -тся, активні дієприкметники)
    for pattern, pattern_reason in RUSSIAN_REGEX_PATTERNS:
        match = pattern.search(lower_text) or pattern.search(norm_lower_text)
        if match:
            matched_word = match.group(0)
            return True, pattern_reason, matched_word

    # 4. Перевірка окремих слів за словником російської лексики
    words = clean_text_words(text)
    norm_words = clean_text_words(norm_text)
    all_word_variants = list(set(words + norm_words))

    for word in all_word_variants:
        if word in UKRAINIAN_WHITELIST:
            continue

        # Прямий збіг зі словником
        if word in RUSSIAN_WORDS_LEXICON:
            return True, f"виявлено російське слово «{word}»", word

    # 5. Fuzzy / Typo перевірка (одруківки типу «блч», «полотнце», «првет»)
    for word in all_word_variants:
        if word in UKRAINIAN_WHITELIST or len(word) < 3:
            continue

        for target in FUZZY_TARGETS:
            # Клавіатурна одруківка (наприклад: блч -> бля)
            if is_keyboard_typo(word, target):
                return True, f"виявлено одруківку російського слова «{target}» (написано «{word}»)", word

            # Відстань Левенштейна (помилка на 1-2 літери)
            dist = levenshtein_distance(word, target)
            if (len(target) <= 4 and dist == 1 and word not in UKRAINIAN_WHITELIST) or \
               (len(target) > 4 and dist <= 1) or \
               (len(target) >= 7 and dist <= 2):
                return True, f"виявлено спробу написати російське слово «{target}» (написано «{word}»)", word

    return False, None, None
