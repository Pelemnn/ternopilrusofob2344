def normalize_leetspeak(text: str) -> str:
    """Нормалізує текст від спроб обійти фільтри спецсимволами (бл@ть -> блять, $ука -> сука)."""
    res = []
    for ch in text.lower():
        if ch in LEET_REPLACEMENTS:
            res.append(LEET_REPLACEMENTS[ch])
        elif ch in "*_`~|/\\":
            continue
        else:
            res.append(ch)
    return "".join(res)


def levenshtein_distance(s1: str, s2: str) -> int:
    """Обчислює відстань Левенштейна між двома рядками."""
    if len(s1) < len(s2):
        return levenshtein_distance(s2, s1)
    if len(s2) == 0:
        return len(s1)

    previous_row = range(len(s2) + 1)
    for i, c1 in enumerate(s1):
        current_row = [i + 1]
        for j, c2 in enumerate(s2):
            insertions = previous_row[j + 1] + 1
            deletions = current_row[j] + 1
            substitutions = previous_row[j] + (c1 != c2)
            current_row.append(min(insertions, deletions, substitutions))
        previous_row = current_row

    return previous_row[-1]


def is_keyboard_typo(word: str, target: str) -> bool:
    """
    Перевіряє, чи є слово одруком цільового слова через сусідні клавіші на клавіатурі (наприклад блч -> бля).
    """
    if len(word) != len(target):
        return False
    diff_count = 0
    for w_ch, t_ch in zip(word, target):
        if w_ch != t_ch:
            diff_count += 1
            if diff_count > 1:
                return False
            if w_ch not in KEYBOARD_NEIGHBORS.get(t_ch, set()) and t_ch not in KEYBOARD_NEIGHBORS.get(w_ch, set()):
                return False
    return diff_count == 1


def clean_text_words(text: str) -> list[str]:
    """Розбиває текст на окремі слова, прибираючи пунктуацію."""
    # Очищуємо від знаків оклику, долара тощо перед розбиттям
    raw_words = re.findall(r"[a-zA-Zа-яА-ЯёЁіІїЇєЄґҐъЪыЫэЭ0-9@$!_'-]+", text)
    result = []
    for w in raw_words:
        cleaned = w.strip("'-").lower()
        if cleaned:
            result.append(cleaned)
    return result


